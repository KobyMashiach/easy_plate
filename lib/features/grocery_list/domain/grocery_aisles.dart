import 'entities/grocery_item_entity.dart';

/// The supermarket's departments, in the order a shopper usually walks them:
/// fresh produce by the door, chilled along the wall, frozen and cleaning
/// last so nothing thaws and nothing leaks onto the food.
enum GroceryAisle {
  produce,
  dairy,
  bakery,
  meat,
  dryGoods,
  frozen,
  cleaning,
  other,
}

/// Which aisle a grocery line belongs to — for ordering the list only.
///
/// A line's stored `category` is used when it already names an aisle; today
/// every line carries the default one, so the name is classified here by
/// keywords in the five app languages. The result is never written back:
/// the category travels with the list to the website and to shared copies,
/// and a guess made for sorting must not become their data.
class GroceryAisles {
  const GroceryAisles._();

  static GroceryAisle of(GroceryItemEntity item) {
    for (final aisle in GroceryAisle.values) {
      if (item.category == aisle.name) return aisle;
    }
    return classify(item.name);
  }

  /// [items] grouped by aisle, aisles in walking order, lines within an aisle
  /// in the order the list had them.
  static List<(GroceryAisle, List<GroceryItemEntity>)> group(
    Iterable<GroceryItemEntity> items,
  ) {
    final by = <GroceryAisle, List<GroceryItemEntity>>{};
    for (final item in items) {
      (by[of(item)] ??= []).add(item);
    }
    return [
      for (final aisle in GroceryAisle.values)
        if (by[aisle] != null) (aisle, by[aisle]!),
    ];
  }

  /// Checked in this order, so "frozen peas" is frozen and not produce, and
  /// "dish soap" is cleaning before anything else can claim "soap".
  static const _order = [
    GroceryAisle.frozen,
    GroceryAisle.cleaning,
    GroceryAisle.meat,
    GroceryAisle.dairy,
    GroceryAisle.bakery,
    GroceryAisle.produce,
    GroceryAisle.dryGoods,
  ];

  static GroceryAisle classify(String name) {
    final text = _normalize(name);
    if (text.isEmpty) return GroceryAisle.other;
    final words = text.split(' ');
    // Phrases first, across every aisle: "peanut butter" is dry goods even
    // though "butter" alone is dairy, "תפוח אדמה" produce though "תפוח" is.
    for (final phrases in [true, false]) {
      for (final aisle in _order) {
        for (final keyword in _keywords[aisle]!) {
          if (keyword.contains(' ') != phrases) continue;
          if (_matches(text, words, keyword)) return aisle;
        }
      }
    }
    return GroceryAisle.other;
  }

  static String _normalize(String s) => s
      .toLowerCase()
      .replaceAll(RegExp(r'[()\[\],.;:!?"״׳/\\-]'), ' ')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();

  /// A phrase keyword (with a space) matches inside the name; a single word
  /// matches a word of the name, or its start when the keyword is long
  /// enough that a prefix still means the same thing ("tomate" in
  /// "tomates", "עגבני" in "עגבניות"). Hebrew and Arabic words may also carry
  /// a one-letter prefix (ה, ו, ال) which is tried off as well. A keyword
  /// written with a leading `=` only ever matches a whole word ("lait" must
  /// not catch "laitue").
  static bool _matches(String text, List<String> words, String keyword) {
    if (keyword.contains(' ')) return text.contains(keyword);
    final exact = keyword.startsWith('=');
    final key = exact ? keyword.substring(1) : keyword;
    for (final word in words) {
      for (final w in _variants(word)) {
        if (w == key) return true;
        if (!exact && key.length >= 4 && w.startsWith(key)) return true;
      }
    }
    return false;
  }

  static Iterable<String> _variants(String word) sync* {
    yield word;
    if (word.length > 3 && (word.startsWith('ה') || word.startsWith('ו'))) {
      yield word.substring(1);
    }
    if (word.length > 4 && word.startsWith('ال')) yield word.substring(2);
  }

