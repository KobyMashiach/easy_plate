async function loadConfig(db) {
  const [doc, priv] = await Promise.all([db.doc(CONFIG_DOC).get(), db.doc(PRIVATE_DOC).get()]);
  const config = cleanConfig(doc.exists ? doc.data() : {});
  const privateKey = priv.exists ? normalizePem(priv.get("applePrivateKey")) : "";
  return { config, privateKey, keyPresent: isPem(privateKey) };
}

async function saveConfig(db, patch) {
  const current = await loadConfig(db);
  const next = cleanConfig({ ...current.config, ...patch });
  await db.doc(CONFIG_DOC).set({ ...next, updatedAt: admin.firestore.FieldValue.serverTimestamp() }, { merge: true });
  if (patch.applePrivateKey !== undefined) {
    const key = normalizePem(patch.applePrivateKey);
    if (key && !isPem(key)) throw Object.assign(new Error("The private key must be the .p8 file's contents (BEGIN PRIVATE KEY)"), { status: 400, code: "invalid" });
    if (key) await db.doc(PRIVATE_DOC).set({ applePrivateKey: key, updatedAt: admin.firestore.FieldValue.serverTimestamp() });
    else await db.doc(PRIVATE_DOC).delete();
  }
  return loadConfig(db);
}

async function writeDays(db, platform, days) {
  const entries = Object.entries(days);
  for (let i = 0; i < entries.length; i += 400) {
    const batch = db.batch();
    for (const [date, data] of entries.slice(i, i + 400)) batch.set(db.doc(`${STATS}/${platform}/days/${date}`), { ...data, date }, { merge: false });
    await batch.commit();
  }
  return entries.length;
}

async function markSync(db, platform, patch) {
  await db.doc(`${STATS}/${platform}`).set({ ...patch, lastSyncAt: admin.firestore.FieldValue.serverTimestamp() }, { merge: true });
}

// The service account the function runs as: the email to invite in the
// Play Console. Cloud Run answers on the metadata server; elsewhere the
// project's default compute account is the usual answer.
async function serviceAccountEmail(fetchImpl = fetch) {
  try {
    const res = await fetchImpl("http://metadata.google.internal/computeMetadata/v1/instance/service-accounts/default/email", { headers: { "Metadata-Flavor": "Google" }, signal: AbortSignal.timeout(1500) });
    if (res.ok) return (await res.text()).trim();
  } catch (_) {}
  const project = process.env.GCLOUD_PROJECT || "";
  return project ? `(the default compute service account of ${project})` : "";
}

