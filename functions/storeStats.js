async function fetchAppleDay({ config, token, date, fetchImpl = fetch }) {
  const params = new URLSearchParams({
    "filter[frequency]": "DAILY",
    "filter[reportDate]": date,
    "filter[reportSubType]": "SUMMARY",
    "filter[reportType]": "SALES",
    "filter[vendorNumber]": config.appleVendor,
  });
  const res = await fetchImpl(`${ASC_HOST}/v1/salesReports?${params}`, { headers: { Authorization: `Bearer ${token}`, Accept: "application/a-gzip" } });
  if (res.status === 404) return { ...parseAppleSales("", config.appleAppId), missing: true };
  if (!res.ok) {
    let detail = "";
    try {
      const json = await res.json();
      detail = json && json.errors && json.errors[0] ? `${json.errors[0].title || ""} ${json.errors[0].detail || ""}`.trim() : "";
    } catch (_) {}
    const hint = res.status === 401 ? "the key, key id or issuer id is wrong" : res.status === 403 ? "the key has no Sales and Reports access, or the vendor number is not yours" : "";
    throw Object.assign(new Error(`App Store Connect ${res.status}${detail ? `: ${detail}` : ""}${hint ? ` (${hint})` : ""}`), { status: 502, code: "apple_access" });
  }
  const bytes = Buffer.from(await res.arrayBuffer());
  let text;
  try {
    text = zlib.gunzipSync(bytes).toString("utf8");
  } catch (_) {
    text = bytes.toString("utf8");
  }
  return parseAppleSales(text, config.appleAppId);
}

// Pulls the days not yet stored (plus the last few, which Apple may still
// correct), or everything since `config.iosSince` on a backfill.
async function syncIos({ db, config, privateKey, fetchImpl = fetch, backfill = false, now = Date.now() }) {
  if (!iosConfigured(config, isPem(privateKey))) throw Object.assign(new Error("App Store Connect not configured"), { status: 400, code: "not_configured" });
  // Yesterday is the newest report Apple has.
  const yesterday = dayKey(new Date(now - DAY_MS));
  const earliest = dayKey(new Date(now - MAX_BACKFILL_DAYS * DAY_MS));
  const stored = await db.collection(`${STATS}/ios/days`).select("date").get();
  const have = new Set(stored.docs.map((d) => d.id));
  const from = config.iosSince && config.iosSince > earliest ? config.iosSince : earliest;
  // Days never stored, plus the newest few whatever is stored.
  const recheckFrom = dayKey(new Date(now - (RECHECK_DAYS + 1) * DAY_MS));
  const wanted = daysBetween(from, yesterday).filter((d) => backfill || !have.has(d) || d >= recheckFrom);
  let token = appleJwt({ issuerId: config.appleIssuerId, keyId: config.appleKeyId, privateKey, now });
  let minted = now;
  const days = {};
  let index = 0;
  const worker = async () => {
    while (index < wanted.length) {
      const date = wanted[index++];
      if (Date.now() - minted > 15 * 60 * 1000) {
        token = appleJwt({ issuerId: config.appleIssuerId, keyId: config.appleKeyId, privateKey });
        minted = Date.now();
      }
      days[date] = await fetchAppleDay({ config, token, date, fetchImpl });
    }
  };
  try {
    await Promise.all(Array.from({ length: Math.min(IOS_CONCURRENCY, wanted.length) }, worker));
  } catch (err) {
    // Whatever was fetched before the failure is kept; the error is shown.
    if (Object.keys(days).length) await writeDays(db, "ios", days);
    await markSync(db, "ios", { error: err.message });
    throw err;
  }
  const written = await writeDays(db, "ios", days);
  const all = await db.collection(`${STATS}/ios/days`).select("date", "downloads", "missing").get();
  const dates = all.docs.map((d) => d.id).sort();
  await markSync(db, "ios", {
    error: null,
    days: dates.length,
    firstDay: dates[0] || null,
    lastDay: dates[dates.length - 1] || null,
    missingDays: all.docs.filter((d) => d.get("missing") === true).length,
  });
  logger.info("app store stats synced", { requested: wanted.length, days: written });
  return { platform: "ios", requested: wanted.length, days: written, lastDay: yesterday };
}

