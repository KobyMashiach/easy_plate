async function status(db, fetchImpl = fetch) {
  const { config, keyPresent } = await loadConfig(db);
  const [androidDoc, iosDoc, serviceAccount] = await Promise.all([db.doc(`${STATS}/android`).get(), db.doc(`${STATS}/ios`).get(), serviceAccountEmail(fetchImpl)]);
  const summary = (doc) => {
    const d = doc.exists ? doc.data() : {};
    const at = d.lastSyncAt && typeof d.lastSyncAt.toMillis === "function" ? d.lastSyncAt.toMillis() : null;
    return { ...d, lastSyncAt: at };
  };
  return {
    config,
    serviceAccount,
    android: { configured: androidConfigured(config), ...summary(androidDoc) },
    ios: { configured: iosConfigured(config, keyPresent), keyPresent, ...summary(iosDoc) },
  };
}

async function stats(db, fetchImpl = fetch) {
  const [state, androidDays, iosDays] = await Promise.all([
    status(db, fetchImpl),
    db.collection(`${STATS}/android/days`).orderBy("date").get(),
    db.collection(`${STATS}/ios/days`).orderBy("date").get(),
  ]);
  const days = { android: androidDays.docs.map((d) => d.data()), ios: iosDays.docs.map((d) => d.data()) };
  return { ...state, days, totals: totals(days) };
}

async function sync({ db, platform = "all", backfill = false, fetchImpl = fetch, storage }) {
  const { config, privateKey, keyPresent } = await loadConfig(db);
  const result = { android: null, ios: null, errors: {} };
  if (platform === "all" || platform === "android") {
    if (androidConfigured(config)) {
      try { result.android = await syncAndroid({ db, config, storage }); } catch (err) { result.errors.android = err.message; }
    } else result.errors.android = "not_configured";
  }
  if (platform === "all" || platform === "ios") {
    if (iosConfigured(config, keyPresent)) {
      try { result.ios = await syncIos({ db, config, privateKey, fetchImpl, backfill }); } catch (err) { result.errors.ios = err.message; }
    } else result.errors.ios = "not_configured";
  }
  // One platform asked for alone, and it failed: say so loudly.
  if (platform !== "all" && result.errors[platform]) {
    throw Object.assign(new Error(result.errors[platform]), { status: result.errors[platform] === "not_configured" ? 400 : 502, code: result.errors[platform] === "not_configured" ? "not_configured" : "store_sync" });
  }
  return result;
}

