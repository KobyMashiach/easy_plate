// Feature dictionaries: src/i18n/<feature>.json, each `{ he, en, ar, fr, ru }`
// with keys prefixed by the feature name ("recipes.title"); check-i18n.mjs
// keeps all five languages in step. The build splits them per language
// (scripts/split-i18n.mjs → src/i18n-gen/<lang>.json) and only the visitor's
// language and English (the fallback) are downloaded, each once.
const FEATURE_LOADERS = import.meta.glob<{ default: Dict }>("../i18n-gen/*.json");
const CORE: Record<Lang, Dict> = { he, en, ar, fr, ru };
const DICT: Record<Lang, Dict> = { he: { ...he }, en: { ...en }, ar: { ...ar }, fr: { ...fr }, ru: { ...ru } };
const loadedLangs = new Set<Lang>();
const pending = new Map<Lang, Promise<void>>();

function loadLang(lang: Lang): Promise<void> {
  if (loadedLangs.has(lang)) return Promise.resolve();
  const inFlight = pending.get(lang);
  if (inFlight) return inFlight;
  const loader = FEATURE_LOADERS[`../i18n-gen/${lang}.json`];
  const p = (loader ? loader() : Promise.resolve({ default: {} as Dict }))
    .then((mod) => {
      DICT[lang] = { ...CORE[lang], ...mod.default };
      loadedLangs.add(lang);
    })
    .catch(() => {
      // Offline or a missing chunk: the core strings still work; retry later.
    })
    .finally(() => pending.delete(lang));
  pending.set(lang, p);
  return p;
}
const EN = (): Dict => DICT.en;

function detect(): Lang {
  const fromUrl = new URLSearchParams(location.search).get("lang");
  let stored: string | null = null;
  try {
    stored = localStorage.getItem("ep-lang");
  } catch (_) {
    stored = null;
  }
  const pick = fromUrl || stored || (navigator.language || "he").slice(0, 2);
  // Own keys only: "?lang=constructor" is truthy on a plain object and
  // would be stored as the language.
  return Object.prototype.hasOwnProperty.call(CORE, pick) ? (pick as Lang) : "en";
}

interface I18n {
  lang: Lang;
  dir: "rtl" | "ltr";
  /// The Intl locale for this language (dates, money, the watermark stamp).
  locale: string;
  setLang: (lang: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  fmtMoney: (minor: number, currency: string) => string;
  fmtDate: (ms: number) => string;
}

const Ctx = createContext<I18n | null>(null);

